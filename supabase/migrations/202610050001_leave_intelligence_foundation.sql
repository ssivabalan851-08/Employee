create or replace function public.get_assigned_handovers()
returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog, public
as $$
declare
  v_profile public.profiles;
  v_result jsonb;
begin
  v_profile := private.require_approved_profile();

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'planId', plan.id,
        'leaveRequestId', plan.leave_request_id,
        'ownerName', owner_profile.name,
        'startDate', request.start_date,
