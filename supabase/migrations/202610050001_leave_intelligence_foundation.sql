create or replace function public.save_handover_plan(
  p_request_id uuid,
  p_payload jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_profile public.profiles;
  v_request public.leave_requests;
  v_backup public.profiles;
  v_plan public.leave_handover_plans;
  v_backup_user_id uuid;
  v_summary text;
  v_items jsonb;
begin
  v_profile := private.require_approved_profile();

  if p_payload is null or jsonb_typeof(p_payload) <> 'object' then
    raise exception 'Handover details must be supplied as an object';
  end if;

  select request.*
  into v_request
  from public.leave_requests request
  where request.id = p_request_id
    and request.user_id = v_profile.id
  for update;

  if not found then
    raise exception 'Leave request not found' using errcode = 'P0002';
  end if;
  if v_request.status <> 'pending' then
    raise exception 'A handover can only be edited while the leave request is pending';
  end if;

  begin
    v_backup_user_id := nullif(p_payload ->> 'backupUserId', '')::uuid;
  exception when invalid_text_representation then
    raise exception 'Select a valid backup employee';
  end;
  v_summary := btrim(coalesce(p_payload ->> 'summary', ''));
  v_items := coalesce(p_payload -> 'items', '[]'::jsonb);

  if v_backup_user_id is null then
    raise exception 'A backup employee is required';
  end if;
  if char_length(v_summary) < 10 or char_length(v_summary) > 2000 then
    raise exception 'Handover summary must contain between 10 and 2000 characters';
  end if;
  if jsonb_typeof(v_items) <> 'array'
     or jsonb_array_length(v_items) < 1
     or jsonb_array_length(v_items) > 50 then
    raise exception 'Add between 1 and 50 handover items';
  end if;
  if exists (
    select 1
    from jsonb_array_elements(v_items) item(value)
    where char_length(btrim(coalesce(item.value ->> 'title', ''))) not between 1 and 160
       or char_length(coalesce(item.value ->> 'details', '')) > 2000
       or char_length(coalesce(item.value ->> 'resourceUrl', '')) > 1000
       or (
         nullif(item.value ->> 'resourceUrl', '') is not null
         and (item.value ->> 'resourceUrl') !~* '^https?://'
       )
  ) then
    raise exception 'One or more handover items contain invalid details';
  end if;

  select backup.*
  into v_backup
  from public.profiles backup
  where backup.id = v_backup_user_id
    and backup.id <> v_profile.id
    and backup.approval_status = 'approved'
    and backup.role = 'employee'
    and lower(btrim(backup.department)) = lower(btrim(v_profile.department));

  if not found then
    raise exception 'The selected backup must be an approved employee in your department';
  end if;

  insert into public.leave_handover_plans (
    leave_request_id,
    employee_id,
    backup_user_id,
    summary,
    status,
    response_comment,
    submitted_at,
    responded_at
  ) values (
    v_request.id,
    v_profile.id,
    v_backup.id,
    v_summary,
    'pending',
    null,
    now(),
    null
  )
  on conflict (leave_request_id) do update
  set backup_user_id = excluded.backup_user_id,
      summary = excluded.summary,
      status = 'pending',
      response_comment = null,
      submitted_at = now(),
      responded_at = null,
      updated_at = now()
  returning * into v_plan;

  delete from public.leave_handover_items item
  where item.plan_id = v_plan.id;

  insert into public.leave_handover_items (
    plan_id,
    position,
    title,
    details,
    due_date,
    resource_url
  )
  select
    v_plan.id,
    item.position::integer,
    btrim(item.value ->> 'title'),
    coalesce(item.value ->> 'details', ''),
    nullif(item.value ->> 'dueDate', '')::date,
    nullif(item.value ->> 'resourceUrl', '')
  from jsonb_array_elements(v_items) with ordinality as item(value, position);

  insert into public.leave_handover_events (
    plan_id,
    actor_id,
    event_type,
    metadata
  ) values (
    v_plan.id,
    v_profile.id,
    'plan_saved',
    jsonb_build_object(
      'backupUserId', v_backup.id,
      'itemCount', jsonb_array_length(v_items)
    )
  );

  insert into public.notifications (user_id, title, message)
  values (
    v_backup.id,
    'Handover acknowledgment requested',
    format(
      '%s assigned you as backup for leave from %s to %s. Review and accept or decline the handover.',
      v_profile.name,
      v_request.start_date,
      v_request.end_date
    )
  );

  return jsonb_build_object(
    'planId', v_plan.id,
    'leaveRequestId', v_request.id,
    'backupUserId', v_backup.id,
    'backupName', v_backup.name,
    'summary', v_plan.summary,
    'items', v_items,
    'status', v_plan.status
  );
end;
$$;

create or replace function public.submit_leave_request_v2(
  p_leave_type text,
  p_start_date date,
  p_end_date date,
  p_reason text,
  p_coverage_snapshot_id uuid default null,
  p_handover jsonb default null
)
returns setof public.leave_requests
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_profile public.profiles;
  v_snapshot public.leave_coverage_snapshots;
  v_evaluation public.leave_policy_evaluations;
  v_request public.leave_requests;
  v_snapshot_id uuid;
  v_preview jsonb;
  v_remaining integer;
  v_overlap boolean;
begin
  v_profile := private.require_approved_profile();

  if p_leave_type not in ('annual', 'sick', 'casual', 'parental') then
    raise exception 'Invalid leave type';
  end if;
  if p_start_date is null or p_end_date is null or p_end_date < p_start_date then
    raise exception 'End date must be on or after start date';
  end if;
  if char_length(btrim(coalesce(p_reason, ''))) = 0 then
    raise exception 'A reason is required';
  end if;

  v_snapshot_id := p_coverage_snapshot_id;
  if v_snapshot_id is null then
    v_preview := public.preview_leave_request(
      p_leave_type,
      p_start_date,
      p_end_date,
      p_reason
    );
    v_snapshot_id := (v_preview ->> 'coverageSnapshotId')::uuid;
  end if;

  select snapshot.*
  into v_snapshot
  from public.leave_coverage_snapshots snapshot
  where snapshot.id = v_snapshot_id
    and snapshot.user_id = v_profile.id
  for update;

  if not found then
    raise exception 'Coverage preview not found' using errcode = 'P0002';
  end if;
  if v_snapshot.used_at is not null then
    raise exception 'This coverage preview has already been used';
  end if;
  if v_snapshot.expires_at < now() then
    raise exception 'This coverage preview has expired. Preview the dates again.';
  end if;
  if v_snapshot.leave_type <> p_leave_type
     or v_snapshot.start_date <> p_start_date
     or v_snapshot.end_date <> p_end_date
     or lower(btrim(v_snapshot.department)) <> lower(btrim(v_profile.department))
     or lower(btrim(v_snapshot.employee_title)) <> lower(btrim(v_profile.title)) then
    raise exception 'The submitted request does not match its coverage preview';
  end if;

  select evaluation.*
  into v_evaluation
  from public.leave_policy_evaluations evaluation
  where evaluation.id = v_snapshot.policy_evaluation_id
    and evaluation.user_id = v_profile.id;

  if not found then
    raise exception 'Policy evaluation not found' using errcode = 'P0002';
  end if;
  if v_evaluation.overall_status = 'fail' then
    raise exception 'This request does not satisfy the leave policy';
  end if;

  select case p_leave_type
    when 'annual' then balance.annual_total - balance.annual_used
    when 'sick' then balance.sick_total - balance.sick_used
    when 'casual' then balance.casual_total - balance.casual_used
    when 'parental' then balance.parental_total - balance.parental_used
  end
  into v_remaining
  from public.leave_balances balance
  where balance.user_id = v_profile.id
  for update;

  if v_snapshot.business_days > greatest(coalesce(v_remaining, 0), 0) then
    raise exception 'The current leave balance is no longer sufficient';
  end if;

  select exists (
    select 1
    from public.leave_requests request
    where request.user_id = v_profile.id
      and request.status in ('pending', 'approved', 'cancellation_pending')
      and daterange(request.start_date, request.end_date, '[]')
          && daterange(p_start_date, p_end_date, '[]')
  ) into v_overlap;

  if v_overlap then
    raise exception 'The selected dates overlap an active leave request';
  end if;

  if v_snapshot.handover_required and p_handover is null then
    raise exception 'A handover plan is required for this request';
  end if;

  insert into public.leave_requests (
    user_id,
    employee_name,
    employee_email,
    department,
    leave_type,
    start_date,
    end_date,
    total_days,
    reason,
    policy_evaluation_id,
    coverage_snapshot_id,
    coverage_risk_level,
    handover_required,
    handover_requirement_reasons
  ) values (
    v_profile.id,
    v_profile.name,
    v_profile.email,
    v_profile.department,
    p_leave_type,
    p_start_date,
    p_end_date,
    v_snapshot.business_days,
    btrim(p_reason),
    v_evaluation.id,
    v_snapshot.id,
    v_snapshot.risk_level,
    v_snapshot.handover_required,
    v_snapshot.handover_reasons
  ) returning * into v_request;

  update public.leave_coverage_snapshots
  set used_at = now()
  where id = v_snapshot.id;

  insert into public.audit_logs (
    leave_id,
    employee_id,
    actor_id,
    actor_name,
    actor_role,
    action,
    previous_status,
    new_status,
    reason
  ) values (
    v_request.id,
    v_profile.id,
    v_profile.id,
    v_profile.name,
    'employee',
    'leave_submitted',
    'none',
    'pending',
    p_reason
  );

  if p_handover is not null then
    perform public.save_handover_plan(v_request.id, p_handover);
  end if;

  return next v_request;
end;
$$;

create or replace function public.respond_to_handover(
  p_plan_id uuid,
  p_response text,
  p_comment text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_profile public.profiles;
  v_plan public.leave_handover_plans;
  v_status text;
begin
  v_profile := private.require_approved_profile();
  v_status := case lower(btrim(coalesce(p_response, '')))
    when 'accept' then 'accepted'
    when 'accepted' then 'accepted'
    when 'decline' then 'declined'
    when 'declined' then 'declined'
    when 'reject' then 'declined'
    when 'rejected' then 'declined'
    else null
  end;

  if v_status is null then
    raise exception 'Response must be accept or decline';
  end if;
  if char_length(coalesce(p_comment, '')) > 2000 then
    raise exception 'Response comment cannot exceed 2000 characters';
  end if;

  select plan.*
  into v_plan
  from public.leave_handover_plans plan
  where plan.id = p_plan_id
    and plan.backup_user_id = v_profile.id
  for update;

  if not found then
    raise exception 'Assigned handover not found' using errcode = 'P0002';
  end if;
  if v_plan.status <> 'pending' then
    raise exception 'This handover has already been answered';
  end if;

  update public.leave_handover_plans
  set status = v_status,
      response_comment = nullif(btrim(coalesce(p_comment, '')), ''),
      responded_at = now(),
      updated_at = now()
  where id = v_plan.id
  returning * into v_plan;

  insert into public.leave_handover_events (
    plan_id,
    actor_id,
    event_type,
    comment
  ) values (
    v_plan.id,
    v_profile.id,
    v_status,
    btrim(coalesce(p_comment, ''))
  );

  insert into public.notifications (user_id, title, message)
  values (
    v_plan.employee_id,
    case when v_status = 'accepted'
      then 'Handover accepted'
      else 'Handover declined' end,
    format(
      '%s %s your handover request.%s',
      v_profile.name,
      v_status,
      case when char_length(btrim(coalesce(p_comment, ''))) = 0
        then '' else ' Comment: ' || btrim(p_comment) end
    )
  );

  return jsonb_build_object(
    'planId', v_plan.id,
    'leaveRequestId', v_plan.leave_request_id,
    'status', v_plan.status,
    'responseComment', v_plan.response_comment,
    'respondedAt', v_plan.responded_at
  );
end;
$$;

create or replace function private.enforce_intelligent_approval()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  if new.status = 'approved' and old.status is distinct from 'approved' then
    if exists (
      select 1
      from public.leave_policy_evaluations evaluation
      where evaluation.id = new.policy_evaluation_id
        and evaluation.overall_status = 'warning'
    ) and char_length(btrim(coalesce(new.manager_comment, ''))) = 0 then
      raise exception 'A manager comment is required for a policy warning';
    end if;

    if new.coverage_risk_level = 'high'
       and char_length(btrim(coalesce(new.approval_override_reason, ''))) < 20 then
      raise exception 'High-risk approval requires an override reason of at least 20 characters';
    end if;

    if new.handover_required and not exists (
      select 1
      from public.leave_handover_plans plan
      where plan.leave_request_id = new.id
        and plan.status = 'accepted'
    ) then
      raise exception 'The assigned backup must accept the required handover before approval';
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists enforce_intelligent_approval on public.leave_requests;
create trigger enforce_intelligent_approval
before update of status on public.leave_requests
for each row execute function private.enforce_intelligent_approval();

create or replace function public.process_leave_request_v2(
  p_request_id uuid,
  p_action text,
  p_comment text default '',
  p_override_reason text default ''
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_manager public.profiles;
  v_request public.leave_requests;
  v_next_status public.leave_status;
  v_remaining integer;
begin
  v_manager := private.require_approved_profile();
  if v_manager.role <> 'manager' or not public.is_manager(v_manager.id) then
    raise exception 'Manager access required' using errcode = '42501';
  end if;
  if p_action not in ('approve', 'reject') then
    raise exception 'Unsupported action';
  end if;
  if char_length(coalesce(p_comment, '')) > 2000 then
    raise exception 'Manager comment cannot exceed 2000 characters';
  end if;

  select request.*
  into v_request
  from public.leave_requests request
  where request.id = p_request_id
  for update;

  if not found then
    raise exception 'Leave request not found' using errcode = 'P0002';
  end if;
  if v_request.status <> 'pending' then
    raise exception 'Only pending requests can be processed';
  end if;

  if exists (
    select 1
    from public.leave_policy_evaluations evaluation
    where evaluation.id = v_request.policy_evaluation_id
      and evaluation.overall_status = 'warning'
  ) and char_length(btrim(coalesce(p_comment, ''))) = 0 then
    raise exception 'A manager comment is required for a policy warning';
  end if;

  if p_action = 'approve' then
    if v_request.coverage_risk_level = 'high'
       and char_length(btrim(coalesce(p_override_reason, ''))) < 20 then
      raise exception 'High-risk approval requires an override reason of at least 20 characters';
    end if;

    if v_request.handover_required and not exists (
      select 1
      from public.leave_handover_plans plan
      where plan.leave_request_id = v_request.id
        and plan.status = 'accepted'
    ) then
      raise exception 'The assigned backup must accept the required handover before approval';
    end if;

    select case v_request.leave_type
      when 'annual' then balance.annual_total - balance.annual_used
      when 'sick' then balance.sick_total - balance.sick_used
      when 'casual' then balance.casual_total - balance.casual_used
      when 'parental' then balance.parental_total - balance.parental_used
    end
    into v_remaining
    from public.leave_balances balance
    where balance.user_id = v_request.user_id
    for update;

    if v_request.total_days > greatest(coalesce(v_remaining, 0), 0) then
      raise exception 'The employee no longer has sufficient leave balance';
    end if;

    update public.leave_balances balance
    set annual_used = balance.annual_used
        + case when v_request.leave_type = 'annual' then v_request.total_days else 0 end,
        sick_used = balance.sick_used
        + case when v_request.leave_type = 'sick' then v_request.total_days else 0 end,
        casual_used = balance.casual_used
        + case when v_request.leave_type = 'casual' then v_request.total_days else 0 end,
        parental_used = balance.parental_used
        + case when v_request.leave_type = 'parental' then v_request.total_days else 0 end,
        updated_at = now()
    where balance.user_id = v_request.user_id;
  end if;

  v_next_status := case when p_action = 'approve'
    then 'approved'::public.leave_status
    else 'rejected'::public.leave_status end;

  update public.leave_requests
  set status = v_next_status,
      manager_comment = p_comment,
      approval_override_reason = case
        when p_action = 'approve' and coverage_risk_level = 'high'
          then btrim(p_override_reason)
        else approval_override_reason end,
      processed_at = now(),
      processed_by = v_manager.id,
      updated_at = now(),
      approved_at = case when p_action = 'approve' then now() else approved_at end,
      rejected_at = case when p_action = 'reject' then now() else rejected_at end
  where id = v_request.id;

  insert into public.notifications (user_id, title, message)
  values (
    v_request.user_id,
    case when p_action = 'approve' then 'Leave approved' else 'Leave request declined' end,
    format(
      'Your %s leave from %s to %s was %s.%s',
      v_request.leave_type,
      v_request.start_date,
      v_request.end_date,
      case when p_action = 'approve' then 'approved' else 'declined' end,
      case when char_length(btrim(coalesce(p_comment, ''))) = 0
        then '' else ' Comment: ' || btrim(p_comment) end
    )
  );

  insert into public.audit_logs (
    leave_id,
    employee_id,
    actor_id,
    actor_name,
    actor_role,
    action,
    previous_status,
    new_status,
    reason
  ) values (
    v_request.id,
    v_request.user_id,
    v_manager.id,
    v_manager.name,
    'hr',
    case when p_action = 'approve' then 'leave_approved' else 'leave_rejected' end,
    'pending',
    v_next_status::text,
    case
      when p_action = 'approve' and v_request.coverage_risk_level = 'high'
        then btrim(p_override_reason)
      else p_comment end
  );
end;
$$;

