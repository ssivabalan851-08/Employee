-- Central, holiday-aware business-day functions. Active government and company
-- calendar events both remove a weekday from the working-day count.
create or replace function private.is_business_day(p_day date)
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select
    extract(isodow from p_day) < 6
    and not exists (
      select 1
      from public.company_calendar_events e
      where e.event_date = p_day
        and e.is_active
    );
$$;

create or replace function private.business_days_between(p_start_date date, p_end_date date)
returns integer
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select case
    when p_start_date is null or p_end_date is null or p_end_date < p_start_date then 0
    else (
      select count(*)::integer
      from generate_series(
        p_start_date::timestamp,
        p_end_date::timestamp,
        interval '1 day'
      ) as days(day_value)
      where private.is_business_day(days.day_value::date)
    )
  end;
$$;

create or replace function private.business_date_after(p_start_date date, p_offset integer)
returns date
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select candidate.day_value::date
  from generate_series(
    p_start_date::timestamp,
    (p_start_date + 730)::timestamp,
    interval '1 day'
  ) with ordinality as candidate(day_value, position)
  where private.is_business_day(candidate.day_value::date)
  order by candidate.day_value
  offset greatest(coalesce(p_offset, 0), 0)
  limit 1;
$$;

create or replace function private.apply_authoritative_business_days()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  if new.end_date < new.start_date then
    raise exception 'End date must be on or after start date';
  end if;

  new.total_days := private.business_days_between(new.start_date, new.end_date);
  if new.total_days < 1 then
    raise exception 'Leave dates must include at least one working day';
  end if;

  return new;
end;
$$;

drop trigger if exists apply_authoritative_business_days on public.leave_requests;
create trigger apply_authoritative_business_days
before insert or update of start_date, end_date on public.leave_requests
for each row execute function private.apply_authoritative_business_days();

create or replace function private.require_approved_profile()
returns public.profiles
language plpgsql
stable
security definer
set search_path = pg_catalog, public
as $$
declare
  v_profile public.profiles;
begin
  if auth.uid() is null then
    raise exception 'Authentication is required' using errcode = '28000';
  end if;

  select p.*
  into v_profile
  from public.profiles p
  where p.id = auth.uid()
    and p.approval_status = 'approved';

  if not found then
    raise exception 'An approved LeaveWise account is required' using errcode = '42501';
  end if;

  return v_profile;
end;
$$;

create or replace function private.create_policy_evaluation(
  p_user_id uuid,
  p_leave_type text,
  p_start_date date,
  p_end_date date,
  p_reason text
)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_policy public.leave_policy_versions;
  v_business_days integer;
  v_notice_days integer;
  v_required_notice integer;
  v_maximum_days integer;
  v_remaining integer;
  v_overlap boolean;
  v_checks jsonb := '[]'::jsonb;
  v_status text := 'pass';
  v_check_status text;
  v_evaluation_id uuid;
begin
  select policy.*
  into v_policy
  from public.leave_policy_versions policy
  where policy.effective_from <= p_start_date
  order by policy.effective_from desc, policy.version_number desc
  limit 1;

  if not found then
    raise exception 'No leave policy is effective for the selected dates';
  end if;

  v_business_days := private.business_days_between(p_start_date, p_end_date);
  v_notice_days := case
    when p_start_date <= current_date then 0
    else private.business_days_between(current_date + 1, p_start_date - 1)
  end;
  v_required_notice := coalesce(
    (v_policy.rules -> 'minimumNoticeBusinessDays' ->> p_leave_type)::integer,
    0
  );
  v_maximum_days := coalesce(
    (v_policy.rules -> 'maximumConsecutiveBusinessDays' ->> p_leave_type)::integer,
    366
  );

  select case p_leave_type
    when 'annual' then b.annual_total - b.annual_used
    when 'sick' then b.sick_total - b.sick_used
    when 'casual' then b.casual_total - b.casual_used
    when 'parental' then b.parental_total - b.parental_used
  end
  into v_remaining
  from public.leave_balances b
  where b.user_id = p_user_id;

  v_remaining := greatest(coalesce(v_remaining, 0), 0);

  select exists (
    select 1
    from public.leave_requests request
    where request.user_id = p_user_id
      and request.status in ('pending', 'approved', 'cancellation_pending')
      and daterange(request.start_date, request.end_date, '[]')
          && daterange(p_start_date, p_end_date, '[]')
  ) into v_overlap;

  v_check_status := case
    when coalesce((v_policy.rules ->> 'allowPastDates')::boolean, false)
      or p_start_date >= current_date then 'pass'
    else 'fail'
  end;
  if v_check_status = 'fail' then v_status := 'fail'; end if;
  v_checks := v_checks || jsonb_build_array(jsonb_build_object(
    'code', 'date_not_in_past',
    'label', 'Requested dates',
    'status', v_check_status,
    'message', case when v_check_status = 'pass'
      then 'The request starts on an allowed date.'
      else 'Leave cannot start in the past.' end
  ));

  v_check_status := case when v_business_days > 0 then 'pass' else 'fail' end;
  if v_check_status = 'fail' then v_status := 'fail'; end if;
  v_checks := v_checks || jsonb_build_array(jsonb_build_object(
    'code', 'business_days',
    'label', 'Working days',
    'status', v_check_status,
    'message', format('%s business day(s), excluding weekends and published holidays.', v_business_days),
    'actual', v_business_days
  ));

  v_check_status := case
    when not coalesce((v_policy.rules ->> 'requireReason')::boolean, true)
      or char_length(btrim(coalesce(p_reason, ''))) > 0 then 'pass'
    else 'fail'
  end;
  if v_check_status = 'fail' then v_status := 'fail'; end if;
  v_checks := v_checks || jsonb_build_array(jsonb_build_object(
    'code', 'reason_required',
    'label', 'Reason supplied',
    'status', v_check_status,
    'message', case when v_check_status = 'pass'
      then 'A reason has been supplied.'
      else 'A reason is required.' end
  ));

  if char_length(btrim(coalesce(p_reason, ''))) between 1 and 9 and v_status <> 'fail' then
    v_status := 'warning';
  end if;
  v_checks := v_checks || jsonb_build_array(jsonb_build_object(
    'code', 'reason_detail',
    'label', 'Reason detail',
    'status', case
      when char_length(btrim(coalesce(p_reason, ''))) = 0 then 'fail'
      when char_length(btrim(p_reason)) < 10 then 'warning'
      else 'pass' end,
    'message', case
      when char_length(btrim(coalesce(p_reason, ''))) = 0 then 'No reason was supplied.'
      when char_length(btrim(p_reason)) < 10 then 'Add a little more detail for a faster review.'
      else 'The reason contains enough detail for review.' end
  ));

  v_check_status := case when v_notice_days >= v_required_notice then 'pass' else 'fail' end;
  if v_check_status = 'fail' then v_status := 'fail'; end if;
  v_checks := v_checks || jsonb_build_array(jsonb_build_object(
    'code', 'minimum_notice',
    'label', 'Notice period',
    'status', v_check_status,
    'message', format('%s of %s required business-day notice provided.', v_notice_days, v_required_notice),
    'actual', v_notice_days,
    'required', v_required_notice
  ));

  v_check_status := case when v_business_days <= v_maximum_days then 'pass' else 'fail' end;
  if v_check_status = 'fail' then v_status := 'fail'; end if;
  v_checks := v_checks || jsonb_build_array(jsonb_build_object(
    'code', 'maximum_duration',
    'label', 'Maximum duration',
    'status', v_check_status,
    'message', format('%s of %s permitted consecutive business days requested.', v_business_days, v_maximum_days),
    'actual', v_business_days,
    'maximum', v_maximum_days
  ));

  v_check_status := case when v_business_days <= v_remaining then 'pass' else 'fail' end;
  if v_check_status = 'fail' then v_status := 'fail'; end if;
  v_checks := v_checks || jsonb_build_array(jsonb_build_object(
    'code', 'leave_balance',
    'label', 'Available balance',
    'status', v_check_status,
    'message', format('%s day(s) requested with %s day(s) available.', v_business_days, v_remaining),
    'requested', v_business_days,
    'available', v_remaining
  ));

  v_check_status := case when not v_overlap then 'pass' else 'fail' end;
  if v_check_status = 'fail' then v_status := 'fail'; end if;
  v_checks := v_checks || jsonb_build_array(jsonb_build_object(
    'code', 'date_overlap',
    'label', 'Existing requests',
    'status', v_check_status,
    'message', case when v_overlap
      then 'The selected dates overlap an active leave request.'
      else 'No active leave request overlaps these dates.' end
  ));

  insert into public.leave_policy_evaluations (
    user_id,
    policy_version_id,
    leave_type,
    start_date,
    end_date,
    business_days,
    overall_status,
    checks,
    reason_present
  ) values (
    p_user_id,
    v_policy.id,
    p_leave_type,
    p_start_date,
    p_end_date,
    v_business_days,
    v_status,
    v_checks,
    char_length(btrim(coalesce(p_reason, ''))) > 0
  ) returning id into v_evaluation_id;

  return v_evaluation_id;
end;
$$;

create or replace function private.calculate_coverage(
  p_user_id uuid,
  p_department text,
  p_employee_title text,
  p_start_date date,
  p_end_date date
)
returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog, public
as $$
declare
  v_rule public.department_coverage_rules%rowtype;
  v_day date;
  v_headcount integer;
  v_approved_absent integer;
  v_pending_requests integer;
  v_projected_available integer;
  v_projected_concurrent integer;
  v_requester_already_absent boolean;
  v_coverage_percent numeric(5,2);
  v_critical_at_risk integer;
  v_daily_facts jsonb := '[]'::jsonb;
  v_min_coverage numeric(5,2) := 100;
  v_min_projected_available integer;
  v_max_concurrent integer := 0;
  v_max_critical_at_risk integer := 0;
  v_coverage_component integer;
  v_concurrency_component integer;
  v_critical_component integer;
  v_risk_score integer;
  v_risk_level text;
begin
  select rule.*
  into v_rule
  from public.department_coverage_rules rule
  where lower(btrim(rule.department)) = lower(btrim(p_department))
    and rule.is_active
    and rule.effective_from <= p_start_date
    and (rule.effective_to is null or rule.effective_to >= p_end_date)
  order by rule.effective_from desc, rule.created_at desc
  limit 1;

  if not found then
    v_rule.minimum_available := 1;
    v_rule.minimum_coverage_percent := 60;
    v_rule.maximum_concurrent_leave := 2;
    v_rule.medium_risk_score := 35;
    v_rule.high_risk_score := 70;
  end if;

  select count(*)::integer
  into v_headcount
  from public.profiles profile
  where profile.approval_status = 'approved'
    and lower(btrim(profile.department)) = lower(btrim(p_department));

  v_min_projected_available := v_headcount;

  for v_day in
    select days.day_value::date
    from generate_series(
      p_start_date::timestamp,
      p_end_date::timestamp,
      interval '1 day'
    ) as days(day_value)
    where private.is_business_day(days.day_value::date)
    order by days.day_value
  loop
    select count(distinct request.user_id)::integer
    into v_approved_absent
    from public.leave_requests request
    where lower(btrim(request.department)) = lower(btrim(p_department))
      and request.status in ('approved', 'cancellation_pending')
      and v_day between request.start_date and request.end_date;

    select exists (
      select 1
      from public.leave_requests request
      where request.user_id = p_user_id
        and request.status in ('approved', 'cancellation_pending')
        and v_day between request.start_date and request.end_date
    ) into v_requester_already_absent;

    select count(distinct request.user_id)::integer
    into v_pending_requests
    from public.leave_requests request
    where lower(btrim(request.department)) = lower(btrim(p_department))
      and request.status = 'pending'
      and request.user_id <> p_user_id
      and v_day between request.start_date and request.end_date;

    v_projected_available := greatest(
      0,
      v_headcount - v_approved_absent - case when v_requester_already_absent then 0 else 1 end
    );
    v_projected_concurrent :=
      v_approved_absent + v_pending_requests + case when v_requester_already_absent then 0 else 1 end;
    v_coverage_percent := case
      when v_headcount = 0 then 0
      else round((v_projected_available::numeric * 100) / v_headcount, 2)
    end;

    select count(*)::integer
    into v_critical_at_risk
    from public.critical_role_rules critical
    where lower(btrim(critical.department)) = lower(btrim(p_department))
      and critical.is_active
      and critical.effective_from <= v_day
      and (critical.effective_to is null or critical.effective_to >= v_day)
      and (
        select count(*)::integer
        from public.profiles candidate
        where candidate.approval_status = 'approved'
          and lower(btrim(candidate.department)) = lower(btrim(p_department))
          and lower(btrim(candidate.title)) = lower(btrim(critical.role_title))
          and candidate.id <> p_user_id
          and not exists (
            select 1
            from public.leave_requests existing_leave
            where existing_leave.user_id = candidate.id
              and existing_leave.status in ('approved', 'cancellation_pending')
              and v_day between existing_leave.start_date and existing_leave.end_date
          )
      ) < critical.minimum_available;

    v_min_coverage := least(v_min_coverage, v_coverage_percent);
    v_min_projected_available := least(v_min_projected_available, v_projected_available);
    v_max_concurrent := greatest(v_max_concurrent, v_projected_concurrent);
    v_max_critical_at_risk := greatest(v_max_critical_at_risk, v_critical_at_risk);

    v_daily_facts := v_daily_facts || jsonb_build_array(jsonb_build_object(
      'date', v_day,
      'departmentHeadcount', v_headcount,
      'approvedAbsent', v_approved_absent,
      'pendingRequests', v_pending_requests,
      'projectedAvailable', v_projected_available,
      'coveragePercent', v_coverage_percent,
      'projectedConcurrentLeave', v_projected_concurrent,
      'criticalRoleRulesAtRisk', v_critical_at_risk
    ));
  end loop;

  v_coverage_component := case
    when v_min_projected_available < v_rule.minimum_available
      or v_min_coverage < v_rule.minimum_coverage_percent
      then least(
        100,
        70
        + greatest(v_rule.minimum_available - v_min_projected_available, 0) * 10
        + greatest(round(v_rule.minimum_coverage_percent - v_min_coverage)::integer, 0)
      )
    else least(60, greatest(0, round((100 - v_min_coverage) * 0.35)::integer))
  end;

  v_concurrency_component := case
    when v_max_concurrent > v_rule.maximum_concurrent_leave
      then least(100, 70 + ((v_max_concurrent - v_rule.maximum_concurrent_leave) * 10))
    else least(
      60,
      round((v_max_concurrent::numeric / greatest(v_rule.maximum_concurrent_leave, 1)) * 40)::integer
    )
  end;

  v_critical_component := case when v_max_critical_at_risk > 0 then 100 else 0 end;
  v_risk_score := least(
    100,
    round(
      (v_coverage_component * 0.45)
      + (v_concurrency_component * 0.20)
      + (v_critical_component * 0.35)
    )::integer
  );

  if v_max_critical_at_risk > 0
     or v_min_projected_available < v_rule.minimum_available then
    v_risk_score := greatest(v_risk_score, v_rule.high_risk_score);
  end if;

  v_risk_level := case
    when v_risk_score >= v_rule.high_risk_score then 'high'
    when v_risk_score >= v_rule.medium_risk_score then 'medium'
    else 'low'
  end;

  return jsonb_build_object(
    'riskScore', v_risk_score,
    'riskLevel', v_risk_level,
    'componentScores', jsonb_build_object(
      'coverage', v_coverage_component,
      'concurrency', v_concurrency_component,
      'criticalRole', v_critical_component,
      'overall', v_risk_score
    ),
    'dailyFacts', v_daily_facts,
    'criticalRoleTriggered', v_max_critical_at_risk > 0,
    'rule', jsonb_build_object(
      'minimumAvailable', v_rule.minimum_available,
      'minimumCoveragePercent', v_rule.minimum_coverage_percent,
      'maximumConcurrentLeave', v_rule.maximum_concurrent_leave,
      'mediumRiskScore', v_rule.medium_risk_score,
      'highRiskScore', v_rule.high_risk_score
    )
  );
end;
$$;

create or replace function public.preview_leave_request(
  p_leave_type text,
  p_start_date date,
  p_end_date date,
  p_reason text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_profile public.profiles;
  v_evaluation public.leave_policy_evaluations;
  v_evaluation_id uuid;
  v_policy_version integer;
  v_coverage jsonb;
  v_candidates jsonb := '[]'::jsonb;
  v_alternatives jsonb := '[]'::jsonb;
  v_candidate_start date;
  v_candidate_end date;
  v_candidate_coverage jsonb;
  v_snapshot_id uuid;
  v_handover_required boolean;
  v_handover_reasons jsonb := '[]'::jsonb;
  v_is_critical_role boolean;
begin
  v_profile := private.require_approved_profile();

  if p_leave_type not in ('annual', 'sick', 'casual', 'parental') then
    raise exception 'Invalid leave type';
  end if;
  if p_start_date is null or p_end_date is null or p_end_date < p_start_date then
    raise exception 'End date must be on or after start date';
  end if;
  if p_end_date - p_start_date > 366 then
    raise exception 'A leave preview cannot span more than 366 calendar days';
  end if;

  v_evaluation_id := private.create_policy_evaluation(
    v_profile.id,
    p_leave_type,
    p_start_date,
    p_end_date,
    p_reason
  );

  select evaluation.*
  into v_evaluation
  from public.leave_policy_evaluations evaluation
  where evaluation.id = v_evaluation_id;

  select policy.version_number
  into v_policy_version
  from public.leave_policy_versions policy
  where policy.id = v_evaluation.policy_version_id;

  if v_evaluation.business_days < 1 then
    raise exception 'Leave dates must include at least one working day';
  end if;

  v_coverage := private.calculate_coverage(
    v_profile.id,
    v_profile.department,
    v_profile.title,
    p_start_date,
    p_end_date
  );

  for v_candidate_start in
    select days.day_value::date
    from generate_series(
      (p_end_date + 1)::timestamp,
      (p_end_date + 90)::timestamp,
      interval '1 day'
    ) as days(day_value)
    where private.is_business_day(days.day_value::date)
    order by days.day_value
  loop
    v_candidate_end := private.business_date_after(
      v_candidate_start,
      v_evaluation.business_days - 1
    );
    v_candidate_coverage := private.calculate_coverage(
      v_profile.id,
      v_profile.department,
      v_profile.title,
      v_candidate_start,
      v_candidate_end
    );
    v_candidates := v_candidates || jsonb_build_array(jsonb_build_object(
      'startDate', v_candidate_start,
      'endDate', v_candidate_end,
      'riskScore', (v_candidate_coverage ->> 'riskScore')::integer,
      'riskLevel', v_candidate_coverage ->> 'riskLevel'
    ));
  end loop;

  select coalesce(jsonb_agg(candidate.item order by candidate.risk_score, candidate.start_date), '[]'::jsonb)
  into v_alternatives
  from (
    select
      value as item,
      (value ->> 'riskScore')::integer as risk_score,
      (value ->> 'startDate')::date as start_date
    from jsonb_array_elements(v_candidates)
    order by (value ->> 'riskScore')::integer, (value ->> 'startDate')::date
    limit 3
  ) candidate;

  if jsonb_array_length(v_alternatives) <> 3 then
    raise exception 'Unable to calculate three alternative date ranges';
  end if;

  select exists (
    select 1
    from public.critical_role_rules critical
    where lower(btrim(critical.department)) = lower(btrim(v_profile.department))
      and lower(btrim(critical.role_title)) = lower(btrim(v_profile.title))
      and critical.is_active
      and critical.effective_from <= p_start_date
      and (critical.effective_to is null or critical.effective_to >= p_end_date)
  ) into v_is_critical_role;

  if v_evaluation.business_days >= 3 then
    v_handover_reasons := v_handover_reasons || '"three_or_more_business_days"'::jsonb;
  end if;
  if v_is_critical_role then
    v_handover_reasons := v_handover_reasons || '"critical_role"'::jsonb;
  end if;
  if v_coverage ->> 'riskLevel' = 'high' then
    v_handover_reasons := v_handover_reasons || '"high_coverage_risk"'::jsonb;
  end if;
  v_handover_required := jsonb_array_length(v_handover_reasons) > 0;

  insert into public.leave_coverage_snapshots (
    user_id,
    policy_evaluation_id,
    department,
    employee_title,
    leave_type,
    start_date,
    end_date,
    business_days,
    risk_score,
    risk_level,
    component_scores,
    handover_required,
    handover_reasons
  ) values (
    v_profile.id,
    v_evaluation.id,
    v_profile.department,
    v_profile.title,
    p_leave_type,
    p_start_date,
    p_end_date,
    v_evaluation.business_days,
    (v_coverage ->> 'riskScore')::integer,
    v_coverage ->> 'riskLevel',
    v_coverage -> 'componentScores',
    v_handover_required,
    v_handover_reasons
  ) returning id into v_snapshot_id;

  insert into public.leave_coverage_snapshot_days (
    snapshot_id,
    day,
    department_headcount,
    approved_absent,
    pending_requests,
    projected_available,
    coverage_percent,
    projected_concurrent_leave,
    critical_role_rules_at_risk
  )
  select
    v_snapshot_id,
    (fact.value ->> 'date')::date,
    (fact.value ->> 'departmentHeadcount')::integer,
    (fact.value ->> 'approvedAbsent')::integer,
    (fact.value ->> 'pendingRequests')::integer,
    (fact.value ->> 'projectedAvailable')::integer,
    (fact.value ->> 'coveragePercent')::numeric,
    (fact.value ->> 'projectedConcurrentLeave')::integer,
    (fact.value ->> 'criticalRoleRulesAtRisk')::integer
  from jsonb_array_elements(v_coverage -> 'dailyFacts') as fact(value);

  insert into public.leave_coverage_alternatives (
    snapshot_id,
    rank,
    start_date,
    end_date,
    risk_score,
    risk_level
  )
  select
    v_snapshot_id,
    alternative.position::smallint,
    (alternative.value ->> 'startDate')::date,
    (alternative.value ->> 'endDate')::date,
    (alternative.value ->> 'riskScore')::integer,
    alternative.value ->> 'riskLevel'
  from jsonb_array_elements(v_alternatives) with ordinality
    as alternative(value, position);

  return jsonb_build_object(
    'policyEvaluationId', v_evaluation.id,
    'policy', jsonb_build_object(
      'status', v_evaluation.overall_status,
      'businessDays', v_evaluation.business_days,
      'checks', v_evaluation.checks,
      'version', v_policy_version,
      'versionId', v_evaluation.policy_version_id
    ),
    'coverageSnapshotId', v_snapshot_id,
    'coverageImpact', v_coverage || jsonb_build_object(
      'recommendedDates', v_alternatives
    ),
    'handoverRequired', v_handover_required,
    'handoverReasons', v_handover_reasons,
    'expiresAt', now() + interval '1 hour'
  );
end;
$$;

