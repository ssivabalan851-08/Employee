create table public.leave_policy_versions (
  id uuid primary key default gen_random_uuid(),
  version_number integer generated by default as identity unique,
  name text not null check (char_length(btrim(name)) between 1 and 120),
  effective_from date not null,
  rules jsonb not null check (jsonb_typeof(rules) = 'object'),
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.leave_policy_evaluations (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  policy_version_id uuid not null references public.leave_policy_versions(id),
  leave_type text not null check (leave_type in ('annual', 'sick', 'casual', 'parental')),
  start_date date not null,
  end_date date not null,
  business_days integer not null check (business_days >= 0),
  overall_status text not null check (overall_status in ('pass', 'warning', 'fail')),
  checks jsonb not null check (jsonb_typeof(checks) = 'array'),
  reason_present boolean not null,
  created_at timestamptz not null default now(),
  check (end_date >= start_date)
);

create table public.department_coverage_rules (
  id uuid primary key default gen_random_uuid(),
  department text not null check (char_length(btrim(department)) between 1 and 120),
  minimum_available integer not null default 1 check (minimum_available >= 0),
  minimum_coverage_percent numeric(5,2) not null default 60
    check (minimum_coverage_percent between 0 and 100),
  maximum_concurrent_leave integer not null default 2 check (maximum_concurrent_leave >= 1),
  medium_risk_score integer not null default 35 check (medium_risk_score between 1 and 99),
  high_risk_score integer not null default 70 check (high_risk_score between 2 and 100),
  effective_from date not null default current_date,
  effective_to date,
  is_active boolean not null default true,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (effective_to is null or effective_to >= effective_from),
  check (high_risk_score > medium_risk_score)
);

create table public.critical_role_rules (
  id uuid primary key default gen_random_uuid(),
  department text not null check (char_length(btrim(department)) between 1 and 120),
  role_title text not null check (char_length(btrim(role_title)) between 1 and 160),
  minimum_available integer not null default 1 check (minimum_available >= 1),
  effective_from date not null default current_date,
  effective_to date,
  is_active boolean not null default true,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (effective_to is null or effective_to >= effective_from)
);

create table public.leave_coverage_snapshots (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  policy_evaluation_id uuid not null references public.leave_policy_evaluations(id),
  department text not null,
  employee_title text not null,
  leave_type text not null check (leave_type in ('annual', 'sick', 'casual', 'parental')),
  start_date date not null,
  end_date date not null,
  business_days integer not null check (business_days > 0),
  risk_score integer not null check (risk_score between 0 and 100),
  risk_level text not null check (risk_level in ('low', 'medium', 'high')),
  component_scores jsonb not null check (jsonb_typeof(component_scores) = 'object'),
  handover_required boolean not null default false,
  handover_reasons jsonb not null default '[]'::jsonb check (jsonb_typeof(handover_reasons) = 'array'),
  expires_at timestamptz not null default (now() + interval '1 hour'),
  used_at timestamptz,
  created_at timestamptz not null default now(),
  check (end_date >= start_date)
);

